'use strict';
// Lists every IPC channel Oto's own code registers (ipcMain.handle/on/handleOnce/once, and webContents/service-worker
// .ipc.*), with where it is, how the gatekeeper treats it (main/ipc-guard.js), whether it has an argument schema
// (main/ipc-schema.js) and its size limit. `node scripts/ipc-inventory.js` writes docs/IPC_INVENTORY.md;
// test/ipc-inventory.test.js fails when the file is out of date, so a new channel can't appear unreviewed.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const FILES = ['main.js', 'account.js', ...fs.readdirSync(path.join(ROOT, 'main')).filter((f) => f.endsWith('.js')).map((f) => `main/${f}`)];
const RE = /(ipcMain|\b\w+\.ipc)\.(handle|handleOnce|on|once)\(\s*(['"`])([^'"`]+)\3/g;

function scan() {
  const out = [];
  for (const rel of FILES.sort()) {
    const src = fs.readFileSync(path.join(ROOT, rel), 'utf8');
    let m;
    while ((m = RE.exec(src))) {
      const line = src.slice(0, m.index).split('\n').length;
      out.push({ channel: m[4], kind: m[2], via: m[1] === 'ipcMain' ? 'ipcMain' : `${m[1].replace(/\..*$/, '')}.ipc`, at: rel, line });
    }
  }
  return out.sort((a, b) => a.channel.localeCompare(b.channel) || a.at.localeCompare(b.at));
}

function describe(list) {
  const guardSrc = fs.readFileSync(path.join(ROOT, 'main', 'ipc-guard.js'), 'utf8');
  const OPEN = new RegExp(guardSrc.match(/const OPEN = \/(.+)\/;/)[1]);
  const BIG = Function(`return (${guardSrc.match(/const BIG = (\{[^}]+\});/)[1]})`)(); // eslint-disable-line no-new-func -- reads the table from Oto's own file
  const { SCHEMAS } = require(path.join(ROOT, 'main', 'ipc-schema.js'));
  return list.map((c) => {
    const open = OPEN.test(c.channel);
    const sender = c.via !== 'ipcMain' ? 'own sender only (per-webContents/worker IPC, not via ipcMain)' : open ? (/^(chromeWebstore\.|chrome\.)/.test(c.channel) ? 'exact Chrome Web Store origin' : 'open (validates itself)') : "Oto's window, top frame only";
    return { ...c, sender, schema: SCHEMAS && SCHEMAS[c.channel] ? 'yes' : '—', limit: c.via !== 'ipcMain' || open ? '—' : `${BIG[c.channel] || 1} MB` };
  });
}

function markdown(rows) {
  const n = rows.length, ui = rows.filter((r) => r.sender.startsWith("Oto's window")).length, sch = rows.filter((r) => r.schema === 'yes').length;
  return `# Oto IPC channel inventory

Generated by \`node scripts/ipc-inventory.js\` from Oto's own source; \`test/ipc-inventory.test.js\` fails when it is out
of date. Libraries' channels (\`crx-*\` from electron-chrome-extensions, \`@ghostery/*\`, \`chromeWebstore.*\`) are
registered inside those libraries and are covered by the rules in \`main/ipc-guard.js\` and
\`docs/SECURITY_REVIEW_1.7.13.md\`.

${n} registrations: ${ui} answer only Oto's own window (top frame of \`src/index.html\`), with a size limit; ${sch} also have
an argument schema. Every one refuses \`__proto__\`/\`constructor\`/\`prototype\` keys (main/ipc-schema.js).

| Channel | Kind | Where | Who may send | Schema | Size limit |
|---|---|---|---|---|---|
${rows.map((r) => `| \`${r.channel}\` | ${r.kind} | ${r.at} | ${r.sender} | ${r.schema} | ${r.limit} |`).join('\n')}
`;
}

module.exports = { scan, describe, markdown };
if (require.main === module) {
  fs.writeFileSync(path.join(ROOT, 'docs', 'IPC_INVENTORY.md'), markdown(describe(scan())));
  console.log('docs/IPC_INVENTORY.md written');
}
